"""Generate local-only baseline artifacts from reviewed, metadata-only MCP evidence."""

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "supabase/baseline"
MIGRATIONS = ROOT / "supabase/migrations"


def quote(value):
    return '"' + value.replace('"', '""') + '"'


def literal(value):
    return "'" + value.replace("'", "''") + "'"


def relation(name):
    return "public." + quote(name)


def column(c):
    assert not c["identity"] and not c["generated"] and not c["collation"], c
    return (quote(c["name"]) + " " + c["type"]
            + (" DEFAULT " + c["default"] if c["default"] is not None else "")
            + (" NOT NULL" if c["not_null"] else ""))


def build():
    remote = json.loads((BASE / "remote-catalog.json").read_text())
    initial_path = BASE / "initial-catalog.json"
    MIGRATIONS.mkdir(exist_ok=True)
    expected = {"20260206190001": "6a2530ad179d27216644f6741e9c6680",
                "20260206190014": "f4046c2b4391216ba4b1152b2fbd7535"}
    provenance = []
    assert len(remote["history"]) == 2
    for row in remote["history"]:
        assert len(row["statements"]) == 1
        payload = row["statements"][0].encode()
        assert hashlib.md5(payload).hexdigest() == expected[row["version"]]
        name = f'{row["version"]}_{row["name"]}.sql'
        (MIGRATIONS / name).write_bytes(payload)
        provenance.append({"file": name, "version": row["version"], "name": row["name"],
                           "bytes": len(payload), "characters": len(row["statements"][0]),
                           "md5": hashlib.md5(payload).hexdigest(),
                           "sha256": hashlib.sha256(payload).hexdigest()})
    (BASE / "provenance.json").write_text(json.dumps({
        "source": "Official Supabase MCP execute_sql; supabase_migrations.schema_migrations",
        "project_ref": "yyxqyziilzgnoztfcjgj", "captured_on": "2026-11-02",
        "encoding": "UTF-8; exact statements[0], no added newline",
        "scope": "Registry payload identity, not proof of historical execution or original source files",
        "catalog_sha256": hashlib.sha256((BASE / "remote-catalog.json").read_bytes()).hexdigest(),
        "migrations": provenance}, indent=2) + "\n")
    if not initial_path.exists():
        print("Recovered exact originals; capture initial local catalog before generating catch-up.")
        return
    initial = json.loads(initial_path.read_text())
    old = {r["name"]: r for r in initial["relations"]}
    out = ["-- LOCAL BASELINE CANDIDATE: observed deployed state, NOT security corrections.",
           "-- Generated by scripts/build-supabase-baseline.py from official MCP catalog evidence.",
           "-- Never execute on production; registration requires separately approved parity proof.",
           "BEGIN;", "SET LOCAL search_path = public, pg_catalog, extensions;",
           "SET LOCAL check_function_bodies = false;"]
    for e in remote["enums"] or []:
        out.append(f'CREATE TYPE {relation(e["name"])} AS ENUM ({", ".join(map(literal, e["labels"]))});')
    for s in remote["sequences"] or []:
        out.append(f'CREATE SEQUENCE {relation(s["name"])} AS {s["type"]} START WITH {s["start"]} '
                   f'INCREMENT BY {s["increment"]} MINVALUE {s["min"]} MAXVALUE {s["max"]} '
                   f'CACHE {s["cache"]} {"CYCLE" if s["cycle"] else "NO CYCLE"};')
    for r in remote["relations"]:
        if r["kind"] != "r":
            continue
        if r["name"] not in old:
            out.append(f'CREATE TABLE {relation(r["name"])} (\n  '
                       + ",\n  ".join(map(column, r["columns"])) + "\n);")
        else:
            before = {c["name"]: c for c in old[r["name"]]["columns"]}
            assert set(before) <= {c["name"] for c in r["columns"]}
            for c in r["columns"]:
                target = f'ALTER TABLE {relation(r["name"])} '
                if c["name"] not in before:
                    out.append(target + "ADD COLUMN " + column(c) + ";")
                else:
                    b = before[c["name"]]
                    assert b["type"] == c["type"] and b["default"] == c["default"], (b, c)
                    if b["not_null"] != c["not_null"]:
                        out.append(target + f'ALTER COLUMN {quote(c["name"])} '
                                   + ("SET" if c["not_null"] else "DROP") + " NOT NULL;")
    out.extend(f["definition"].rstrip().rstrip(";") + ";" for f in remote["functions"])
    previous = {(c["table"], c["name"]): c for c in initial["constraints"]}
    foreign_keys = []
    for c in sorted(remote["constraints"], key=lambda c: c["definition"].startswith("FOREIGN KEY")):
        prior = previous.pop((c["table"], c["name"]), None)
        if prior == c:
            continue
        assert prior is None, (prior, c)
        statement = f'ALTER TABLE {relation(c["table"])} ADD CONSTRAINT {quote(c["name"])} {c["definition"]};'
        (foreign_keys if c["definition"].startswith("FOREIGN KEY") else out).append(statement)
    assert not previous, previous
    initial_indexes = {i["name"] for i in initial["indexes"]}
    out.extend(i["definition"] + ";" for i in remote["indexes"]
               if not i["constraint"] and i["name"] not in initial_indexes)
    out.extend(foreign_keys)
    for r in remote["relations"]:
        assert r["owner"] == "postgres"
        if r["kind"] == "v":
            options = " WITH (" + ", ".join(r["options"]) + ")" if r["options"] else ""
            out.append(f'CREATE VIEW {relation(r["name"])}{options} AS {r["view"]}')
        if r["rls"]:
            out.append(f'ALTER TABLE {relation(r["name"])} ENABLE ROW LEVEL SECURITY;')
        if r["force_rls"]:
            out.append(f'ALTER TABLE {relation(r["name"])} FORCE ROW LEVEL SECURITY;')
    for t in remote["triggers"]:
        out.append(t["definition"] + ";")
        if t["enabled"] != "O":
            raise ValueError("Unsupported non-default trigger mode")
    policies = {(p["table"], p["name"]) for p in initial["policies"]}
    for p in remote["policies"]:
        if (p["table"], p["name"]) in policies:
            assert p in initial["policies"]
            continue
        roles = ", ".join("PUBLIC" if r == "public" else quote(r) for r in p["roles"])
        out.append(f'CREATE POLICY {quote(p["name"])} ON {relation(p["table"])} AS {p["permissive"]} '
                   f'FOR {p["command"]} TO {roles}'
                   + (f' USING ({p["using"]})' if p["using"] else "")
                   + (f' WITH CHECK ({p["check"]})' if p["check"] else "") + ";")
    # Explicit ACLs reproduce live access, including the known anonymous helper grants.
    for r in remote["relations"] + remote["functions"]:
        function = "identity" in r
        kind = "FUNCTION" if function else "SEQUENCE" if r["kind"] == "S" else "TABLE"
        target = relation(r["name"]) + ("(" + r["identity"] + ")" if function else "")
        out.append(f'REVOKE ALL ON {kind} {target} FROM PUBLIC, anon, authenticated, service_role;')
        for a in r["acl"] or []:
            assert a["grantor"] == "postgres" and not a["grantable"], a
            role = "PUBLIC" if a["grantee"] == "PUBLIC" else quote(a["grantee"])
            out.append(f'GRANT {a["privilege"]} ON {kind} {target} TO {role};')
    out.append("REVOKE ALL ON SCHEMA public FROM PUBLIC, anon, authenticated, service_role;")
    for a in remote["schema_acl"]:
        role = "PUBLIC" if a["grantee"] == "PUBLIC" else quote(a["grantee"])
        out.append(f'GRANT {a["privilege"]} ON SCHEMA public TO {role};')
    defaults = remote["defaults"]
    managed_defaults = ["-- OBSERVED platform-owned defaults; evidence only, NOT an active migration."]
    for owner, schema, kind in sorted({(d["owner"], d["schema"], d["type"]) for d in defaults}):
        assert schema == "public"
        target = {"r": "TABLES", "f": "FUNCTIONS", "S": "SEQUENCES"}[kind]
        prefix = f'ALTER DEFAULT PRIVILEGES FOR ROLE {quote(owner)} IN SCHEMA public '
        # Supabase-managed owner defaults are retained verbatim; changing them may require
        # a privileged local bootstrap rather than the postgres migration role.
        destination = out if owner == "postgres" else managed_defaults
        destination.append(prefix + f'REVOKE ALL ON {target} FROM PUBLIC, anon, authenticated, service_role;')
        for d in defaults:
            if (d["owner"], d["schema"], d["type"]) == (owner, schema, kind):
                assert not d["grantable"]
                role = "PUBLIC" if d["grantee"] == "PUBLIC" else quote(d["grantee"])
                destination.append(prefix + f'GRANT {d["privilege"]} ON {target} TO {role};')
    (BASE / "managed-owner-defaults.sql").write_text("\n".join(managed_defaults) + "\n")
    out.append("COMMIT;")
    (MIGRATIONS / "20261102170000_reconcile_legacy_through_056.sql").write_text("\n\n".join(out) + "\n")
    print("Generated observed-state catch-up candidate; replay and parity review still required.")


if __name__ == "__main__":
    build()
