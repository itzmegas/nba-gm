CREATE EXTENSION IF NOT EXISTS pgcrypto;
DO $$ BEGIN CREATE ROLE anon NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN CREATE ROLE authenticated NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN CREATE ROLE service_role NOLOGIN BYPASSRLS; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
ALTER ROLE service_role BYPASSRLS;
CREATE SCHEMA auth;
CREATE TABLE auth.users(id UUID PRIMARY KEY);
CREATE FUNCTION auth.uid() RETURNS UUID LANGUAGE sql STABLE AS $$
  SELECT NULLIF(current_setting('request.jwt.claim.sub', true), '')::UUID
$$;
CREATE FUNCTION auth.role() RETURNS TEXT LANGUAGE sql STABLE AS $$
  SELECT NULLIF(current_setting('request.jwt.claim.role', true), '')
$$;

CREATE TABLE teams(id UUID PRIMARY KEY);
CREATE TABLE players(
  id UUID PRIMARY KEY,
  is_active BOOLEAN NOT NULL DEFAULT true,
  years_of_experience SMALLINT
);
CREATE TYPE game_status AS ENUM ('initializing', 'active', 'archived', 'deleted');
CREATE TABLE games(
  id UUID PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id),
  selected_team_id UUID NOT NULL REFERENCES teams(id),
  season_year INTEGER NOT NULL,
  season_era_id TEXT NOT NULL DEFAULT 'modern',
  simulation_date DATE NOT NULL,
  status game_status NOT NULL,
  deleted_at TIMESTAMPTZ
);
CREATE TABLE game_player_states(
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  game_id UUID NOT NULL REFERENCES games(id),
  player_id UUID NOT NULL REFERENCES players(id),
  team_id UUID REFERENCES teams(id),
  is_active BOOLEAN NOT NULL DEFAULT true,
  UNIQUE (game_id, player_id)
);
CREATE TABLE contracts(
  game_id UUID NOT NULL,
  player_id UUID NOT NULL,
  start_year INTEGER NOT NULL,
  end_year INTEGER NOT NULL,
  salary_y1 BIGINT NOT NULL DEFAULT 0,
  salary_y2 BIGINT NOT NULL DEFAULT 0,
  salary_y3 BIGINT NOT NULL DEFAULT 0,
  salary_y4 BIGINT NOT NULL DEFAULT 0,
  salary_y5 BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE game_contract_materializations(game_id UUID PRIMARY KEY REFERENCES games(id));
CREATE TABLE game_contract_agreements(
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  game_id UUID NOT NULL,
  player_id UUID NOT NULL,
  team_id UUID NOT NULL,
  UNIQUE (game_id, player_id)
);
CREATE TABLE game_contract_seasons(
  agreement_id UUID NOT NULL,
  game_id UUID NOT NULL,
  start_year INTEGER NOT NULL,
  salary_amount BIGINT
);

